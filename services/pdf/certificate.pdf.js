const PDFDocument = require("pdfkit");

const generateCertificatePDF = (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ layout: "landscape", margin: 0 });
    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    // Background
    doc.rect(0, 0, 842, 595).fill("#fafafa");

    // Outer border
    doc.rect(30, 30, 782, 535).lineWidth(4).stroke("#4F46E5");
    // Inner border
    doc.rect(40, 40, 762, 515).lineWidth(1).stroke("#4F46E5");
    // Decorative corners
    doc.rect(50, 50, 60, 3).fill("#4F46E5");
    doc.rect(50, 50, 3, 60).fill("#4F46E5");
    doc.rect(732, 50, 60, 3).fill("#4F46E5");
    doc.rect(789, 50, 3, 60).fill("#4F46E5");
    doc.rect(50, 552, 60, 3).fill("#4F46E5");
    doc.rect(50, 495, 3, 60).fill("#4F46E5");
    doc.rect(732, 552, 60, 3).fill("#4F46E5");
    doc.rect(789, 495, 3, 60).fill("#4F46E5");

    // Header
    doc.fontSize(12).fillColor("#9ca3af").text("KKIT", 0, 70, { align: "center" });
    doc.moveDown(0.2);
    doc.fontSize(16).fillColor("#4F46E5").text("CERTIFICATE", { align: "center" });
    doc.fontSize(10).fillColor("#9ca3af").text("OF COMPLETION", { align: "center" });

    // Decorative line
    doc.moveTo(300, 120).lineTo(542, 120).lineWidth(2).stroke("#4F46E5");
    doc.circle(421, 120, 5).fill("#4F46E5");

    // This certifies
    doc.fontSize(11).fillColor("#6b7280").text("This is to certify that", 0, 145, { align: "center" });

    // Student name
    doc.fontSize(32).fillColor("#111827").text(data.studentName, 0, 170, { align: "center", width: 800 });

    // Name underline
    doc.moveTo(200, 215).lineTo(642, 215).lineWidth(1).stroke("#d1d5db");

    // Has completed
    doc.fontSize(11).fillColor("#6b7280").text("has successfully completed the course", 0, 235, { align: "center" });

    // Course name
    doc.fontSize(22).fillColor("#4F46E5").text(data.courseName, 0, 265, { align: "center", width: 700 });

    // Date and Certificate number
    doc.fontSize(10).fillColor("#6b7280");
    doc.text(`Issued: ${data.date}`, 200, 340, { align: "center", width: 200 });
    doc.text(`Certificate #: ${data.certificateNumber}`, 442, 340, { align: "center", width: 200 });

    // Signature section
    doc.moveTo(120, 450).lineTo(280, 450).lineWidth(1).stroke("#9ca3af");
    doc.fontSize(9).fillColor("#6b7280").text("Program Director", 120, 460, { width: 160, align: "center" });

    doc.moveTo(371, 450).lineTo(471, 450).lineWidth(1).stroke("#9ca3af");
    doc.text("Date", 371, 460, { width: 100, align: "center" });

    doc.moveTo(562, 450).lineTo(722, 450).lineWidth(1).stroke("#9ca3af");
    doc.text("Instructor", 562, 460, { width: 160, align: "center" });

    // QR Code placeholder area
    if (data.verificationUrl) {
      doc.fontSize(7).fillColor("#9ca3af");
      doc.text("Scan to verify", 700, 510, { width: 100, align: "center" });
      doc.text(data.verificationUrl, 700, 520, { width: 100, align: "center" });
    }

    // Footer
    doc.fontSize(8).fillColor("#d1d5db").text("This certificate was generated by KKIT Learning Platform", 0, 555, { align: "center" });

    doc.end();
  });
};

module.exports = { generateCertificatePDF };
